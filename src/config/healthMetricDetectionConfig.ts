export type ConfidenceTier = "high" | "medium" | "low";

/** 与每条正则一一对应：显式单位/结构化表述偏高；承接短答、模糊匹配偏低 */
export const CONFIDENCE_SCORE: Record<ConfidenceTier, number> = {
  high: 0.92,
  medium: 0.85,
  low: 0.68,
};

export function confidenceScoreForTier(tier: ConfidenceTier | undefined): number {
  return CONFIDENCE_SCORE[tier ?? "medium"];
}

